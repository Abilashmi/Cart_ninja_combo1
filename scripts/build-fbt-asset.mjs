/* eslint-env node */
// Builds extensions/cart-drawer/assets/brix_fbt.js: the storefront runtime
// (app/storefront/fbt-runtime.js) with the shared FBT core
// (app/utils/fbt-core.shared.js createFbtCore) put in at its marker.
// Run: npm run build:fbt   (tests/fbt checks the asset is up to date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createFbtCore } from '../app/utils/fbt-core.shared.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ASSET = path.join(root, 'extensions/cart-drawer/assets/brix_fbt.js');

export function buildFbtAsset() {
  const runtime = fs.readFileSync(path.join(root, 'app/storefront/fbt-runtime.js'), 'utf8');
  const marker = '/*__FBT_CORE__*/ function () { return null; }';
  if (!runtime.includes(marker)) throw new Error(`fbt-runtime.js has no ${marker}`);
  const out = '/* GENERATED by scripts/build-fbt-asset.mjs - edit app/storefront/fbt-runtime.js and app/utils/fbt-core.shared.js, then npm run build:fbt */\n'
    + runtime.replace(marker, createFbtCore.toString());
  const nonAscii = [...out].filter((c) => c.charCodeAt(0) > 127);
  if (nonAscii.length) throw new Error(`brix_fbt.js must be ASCII only, found: ${[...new Set(nonAscii)].join(' ')}`);
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(ASSET, buildFbtAsset());
  console.log(`wrote ${path.relative(root, ASSET)}`);
}
